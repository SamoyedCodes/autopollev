def _(key: str, **kwargs) -> str:
    """
    Return the English string for a translation key.

    :param key: translation key
    :param kwargs: format variables
    :return: the string, formatted with str.format(**kwargs)
    """
    text = TRANSLATIONS.get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except KeyError:
            pass
    return text
